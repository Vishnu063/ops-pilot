"""Explicit contract for optional API providers.

Native Docker profiles intentionally keep their existing Pilot/triage engine;
remote API approvals never replace or authorize that engine's approval store.
"""
from typing import Protocol


class Provider(Protocol):
    def connection(self): ...
    def discover(self): ...
    def servers(self): ...
    def inspect(self, target): ...
    def deployments(self, target): ...
    def deployment(self, deployment_id, target): ...
    def logs(self, target): ...
    def execute(self, target, action): ...
